#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <stdint.h>
#include <stdbool.h>
#include "isa.h"
#include "bytecode.h"
#include "cpu.h"

int main(int argc, char* argv[])
{
    if (argc != 3)
    {
        fprintf(stderr, "usage: %s <bytecode_in> <text_out>\n", argv[0]);
        return 1;
    }

    int size = 0;
    Elem_t* bytecode = bytecode_read(argv[1], &size);
    if (bytecode == NULL)
    {
        return 1;
    }

    int res = disassembler(argv[2], bytecode, size);

    free(bytecode);
    return res == 0 ? 0 : 1;
}
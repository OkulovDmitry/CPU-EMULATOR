#ifndef ISA_H
#define ISA_H

#include "stack.h"

//#define CPUDEBUG

#define CMD_MASK 0x1F      // младшие 5 бит - номер команды
#define BIT_IMM  (1 << 5)  // дальше идёт число
#define BIT_REG  (1 << 6)  // дальше идёт регистр
#define BIT_MEM  (1 << 7)  // операнд в оперативке
#define BIT_FLT  (1 << 8)  // операнд-число хранит биты double

#define CELL_OP(cell)    ((int)((cell) & (CMD_MASK)))            //ячейка операции
#define CELL_FLAGS(cell) ((int)((cell) & (~(code_t)(CMD_MASK)))) //ячейка с флагами

#define REG_COUNT 4

//===== Одна ячейка байт-кода =====
typedef uint64_t code_t;
//=================================

//====== Opcode - хранит код процессорной операции ======
typedef enum 
{
    CMD_HLT  = 0,
    CMD_PUSH = 1,
    CMD_ADD  = 2,
    CMD_SUB  = 3,
    CMD_MUL  = 4,
    CMD_DIV  = 5,
    CMD_OUT  = 6,
    CMD_POP  = 7,
    CMD_JMP  = 8,
    CMD_JA   = 9,
    CMD_JAE  = 10,
    CMD_JB   = 11,
    CMD_JBE  = 12,
    CMD_JE   = 13,
    CMD_JNE  = 14,
    CMD_CALL = 15,
    CMD_RET  = 16,
    CMD_DRAW = 17,

    CMD_COUNT           // определяет количество команд
} Opcode;
//=======================================================

//=== ComandInfo - структура хранящая название процессорной команды и её тип ===
typedef struct
{
    const char* name;
    int         allowed;   // разврешённые флаги
    int         is_jump;   // 1, если команда в качестве аргумента может принимать метки
} CommandInfo;
//==============================================================================

//==== isa - этот массив определяет какие команды может исполнять процессор на физическом уровне и определяет их тип ====//
extern const CommandInfo isa[CMD_COUNT];
//=======================================================================================================================//

//==== reg_names - этот массив задает количество регистров процессора и их имена ====
extern const char* const reg_names[REG_COUNT];
//===================================================================================

bool is_valid_opcode(code_t v);       // проверяет валидность команды к процессору

bool isa_cell_ok(code_t cell);        // номер и флаги допустимы вместе
int  operand_cells(int flags);        // сколько ячеек операндов идёт после

int  find_command( const char* word); // функция распознания команды
int  find_register(const char* word); // функция распознания регистра
bool is_mem(char* word);             // функция распознания видеопамяти

code_t double_to_cell(Elem_t d);      // переносит 64 бита double в uint64_t
Elem_t cell_to_double(code_t c);      // переносит 64 битф uint64_t в double


#endif //ISA_H
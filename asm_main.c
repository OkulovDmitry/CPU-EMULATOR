#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <stdint.h>
#include <stdbool.h>
#include "isa.h"
#include "bytecode.h"
#include "cpu.h"

int main(int argc, char* argv[])
{
    if (argc != 3)
    {
        fprintf(stderr, "usage: %s <text_in> <bytecode_out>\n", argv[0]);
        return 1;
    }

    int size = 0;
    Elem_t* bytecode = assembler(argv[1], &size);
    if (bytecode == NULL)
    {
        return 1;
    }

    int res = bytecode_write(argv[2], bytecode, size);

    free(bytecode);
    return (bytecode != NULL && res == 0) ? 0 : 1;
}